import test from "node:test";
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { randomUUID } from "node:crypto";
const project = "demo-penguin-hybrid";
if (process.env.GCLOUD_PROJECT !== project || !/^(localhost|127\.0\.0\.1):\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST || "")) throw Error("LOCAL_DEMO_FIRESTORE_REQUIRED");
const require = createRequire(new URL("../../functions/package.json", import.meta.url));
const {initializeApp}=require("firebase-admin/app");
const {getFirestore}=require("firebase-admin/firestore");
initializeApp({projectId:project});
const db=getFirestore();
const history=require("./revenue-share").getPlatformRevenueSharePaymentHistory;
const pricing=require("./subscription-pricing");
const status=require("./stripe-wallet-sandbox").getPlatformStripeWalletSandboxStatus;
const {bangkokDateKey}=require("./billing-anniversary");
const aid="p1-sandbox-admin-"+randomUUID(),oid="p1-sandbox-owner-"+randomUUID();
const auth={uid:aid},owner={uid:oid};
test("actual Firestore callable reads tenant-scoped payment history without slip data",async()=>{
 await db.collection("users").doc(aid).set({role:"super_admin",active:true});
 await db.collection("users").doc(oid).set({role:"owner",active:true});
 const id="p1-history-"+randomUUID(),other="p1-history-"+randomUUID();
 const ref=db.collection("tenants").doc(id),otherRef=db.collection("tenants").doc(other);
 await Promise.all([ref.set({name:"Demo sample"}),otherRef.set({name:"Other sample"})]);
 await ref.collection("revenueSharePayments").doc("p1").set({status:"approved",platformAmountDue:75,createdAt:new Date("2026-11-21T00:00:00Z"),slipPath:"private-demo",slipVerificationProvider:"slip2go"});
 await ref.collection("revenueSharePayments").doc("p2").set({status:"pending",platformAmountDue:125,createdAt:new Date("2026-11-22T00:00:00Z")});
 await otherRef.collection("revenueSharePayments").doc("p3").set({status:"approved",platformAmountDue:999,createdAt:new Date("2026-11-22T00:00:00Z")});
 const result=await history.run({auth,data:{tenantId:id,status:"approved"}});
 assert.equal(result.source,"firebase_revenue_share_payment_records");assert.equal(result.items.length,1);assert.equal(result.items[0].amountCents,7500);
 assert.equal(result.items[0].paymentId,"p1");assert.equal(JSON.stringify(result).includes("private-demo"),false);
 await assert.rejects(history.run({auth:owner,data:{tenantId:id,status:"all"}}),{code:"permission-denied"});
});
test("actual Firestore threshold transaction serializes conflicting requests and locks baseline",async()=>{
 const ref=db.collection("platformSettings").doc("subscriptionPricing");
 const config={monthlyPrice:590,deliveryThreshold:10000,deliveryShareRate:5,monthlySlipQuota:100,annualMonths:12,discountType:"amount",discountValue:1180,vatMode:"inclusive",vatRate:7};
 await ref.set(config);
 const date=bangkokDateKey(new Date(Date.now()+2*86400000));
 const v={effectiveOn:date,thresholdCents:1500000,baselineThresholdCents:1000000};
 await assert.rejects(pricing.appendDeliveryThresholdVersion.run({auth:owner,data:v}),{code:"permission-denied"});
 const results=await Promise.allSettled([pricing.appendDeliveryThresholdVersion.run({auth,data:v}),pricing.appendDeliveryThresholdVersion.run({auth,data:{...v,thresholdCents:2000000}})]);
 assert.equal(results.filter(r=>r.status==="fulfilled").length,1);
 const read=await pricing.getDeliveryThresholdVersions.run({auth,data:{}});
 assert.equal(read.versions.length,1);assert.equal(read.baselineThresholdCents,1000000);
 await assert.rejects(pricing.updateSubscriptionPricing.run({auth,data:{...config,deliveryThreshold:20000}}),{code:"failed-precondition"});
 const updated=await pricing.updateSubscriptionPricing.run({auth,data:{...config,monthlyPrice:650}});
 assert.equal(updated.config.monthlyPrice,650);
 assert.equal((await ref.get()).data().deliveryThresholdVersions.length,1);
});
test("Stripe callable remains disabled on demo Firestore even with verify requested",async()=>{
 const result=await status.run({auth,data:{verify:true}});
 assert.equal(result.enabled,false);assert.equal(result.webhookReady,false);assert.equal(result.checkoutEnabled,false);
 await assert.rejects(status.run({auth:owner,data:{verify:true}}),{code:"permission-denied"});
});
